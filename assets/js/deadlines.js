  function computePairs(eds) {
    var byA = {}, byB = {}, list = [];
    var withDec = eds.filter(function (e) { return e.dNot; }), withDl = eds.filter(function (e) { return e.dDl; });
    withDec.forEach(function (a) {
      withDl.forEach(function (b) {
        if (a === b || a.conf === b.conf && a.year === b.year) return;
        var gap = dayDiff(a.dNot, b.dDl);
        if (gap < -3 || gap > F.maxGap) return;           // keep "3 days too late" so it can be flagged
        if (F.sameField && !a.conf.fields.some(function (f) { return b.conf.fields.indexOf(f) >= 0; })) return;
        var p = { a: a, b: b, gap: gap, absGate: !!(b.dAbs && a.dNot > b.dAbs) };
        list.push(p); (byA[a.id] = byA[a.id] || []).push(p); (byB[b.id] = byB[b.id] || []).push(p);
      });
    });
    Object.keys(byA).forEach(function (k) { byA[k].sort(function (p, q) { return p.b.dDl - q.b.dDl; }); });
    Object.keys(byB).forEach(function (k) { byB[k].sort(function (p, q) { return q.gap - p.gap; }); });
    return { list: list, byA: byA, byB: byB };
  }
